#!/usr/bin/env python3
"""Generate W6A8 candidate registration and ordered exact-shape dispatch.

The manifest owns stable IDs and launch metadata. Exact rules select a config;
the candidate switch executes it using the original launch arguments.
Expressions in exact_rules are trusted, repository-owned C++ expressions.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "python/mxfp6/w6a8_dispatch.json"


def load_policy(source: Path) -> dict:
    policy = json.loads(source.read_text())
    if policy["version"] != 1:
        raise ValueError("unsupported W6A8 policy version")
    candidates = policy["candidates"]
    if [c["id"] for c in candidates] != list(range(len(candidates))):
        raise ValueError("candidate IDs must be contiguous and ordered")
    if len({c["name"] for c in candidates}) != len(candidates):
        raise ValueError("candidate names must be unique")
    for c in candidates:
        launch = c["launch"]
        if launch["kind"] not in ("normal", "swapped", "normal_128"):
            raise ValueError("unknown launch kind")
        if launch["kind"] != "normal_128" and launch["sm_count"] not in ("0", "sm_count"):
            raise ValueError("invalid SM-count policy")
        if c["scheduler"] not in ("default", "static", "stream_k"):
            raise ValueError("unknown scheduler")
        if len(c["tile"]) != 3 or any(type(v) is not int or v <= 0 for v in c["tile"]):
            raise ValueError("invalid tile")
        if c["stages"] != "auto" and (type(c["stages"]) is not int or c["stages"] <= 0):
            raise ValueError("invalid stage count")
        fallback = c.get("disabled_stream_k_fallback")
        if fallback is not None and (fallback not in range(len(candidates)) or fallback == c["id"]):
            raise ValueError("invalid Stream-K fallback")

    def validate_rules(rules):
        for rule in rules:
            if "if" in rule:
                if set(rule) != {"if", "then"} or not rule["if"]:
                    raise ValueError("invalid conditional rule")
                validate_rules(rule["then"])
            elif set(rule) != {"config", "swizzle", "raster"} or rule["config"] not in range(len(candidates)):
                raise ValueError("invalid launch rule")
    validate_rules(policy["exact_rules"])
    return policy


def launch_call(candidate: dict, swizzle: str, raster: str) -> str:
    launch = candidate["launch"]
    args = "a, b, sfa, sfb, m, n, k, alpha, device_index,"
    if launch["kind"] == "normal_128":
        return (f"launch_w6a8_128({args} sm_count, W6A8Kernel128::{launch['kernel']}, "
                f"{swizzle}, {raster}, use_pdl)")
    kind = launch["kind"]
    return (f"launch_{kind}<{kind}::{launch['kernel']}>({args} "
            f"{swizzle}, {raster}, 1, {launch['sm_count']}, use_pdl)")


def generate(policy: dict) -> dict[str, str]:
    candidates = policy["candidates"]
    banner = "// Generated by scripts/generate_w6a8_dispatch.py; edit w6a8_dispatch.json.\n"
    switch = ["switch (config_id) {"]
    for c in candidates:
        switch.append(f"  case {c['id']}:")
        if "disabled_stream_k_fallback" in c:
            fallback = candidates[c["disabled_stream_k_fallback"]]
            switch += ["    if (!stream_k_enabled()) {",
                       "      return " + launch_call(fallback, "swizzle_value", "raster") + ";",
                       "    }"]
        switch.append("    return " + launch_call(c, "swizzle_value", "raster") + ";")
    switch.append("}")

    def emit_rules(rules, indent=""):
        lines = []
        for rule in rules:
            if "if" in rule:
                lines.append(indent + f"if ({rule['if'].replace('current_output_dtype == at::kHalf', 'half_output')}) {{")
                lines.extend(emit_rules(rule["then"], indent + "  "))
                lines.append(indent + "}")
            else:
                lines.append(indent + f"return Config{{{rule['config']}, {rule['swizzle']}, "
                             f"static_cast<int64_t>({rule['raster']})}};")
        return lines

    metadata = [
        '# Generated by scripts/generate_w6a8_dispatch.py; edit w6a8_dispatch.json.',
        f'CANDIDATE_ABI = {policy["candidate_abi"]!r}',
        'KERNEL_NAMES = (',
        *(f'    {c["name"]!r},' for c in candidates),
        ')',
        'STREAM_K_CONFIG_IDS = frozenset(' + repr(tuple(c['id'] for c in candidates if c['scheduler'] == 'stream_k')) + ')',
    ]
    return {
        "w6a8_registry.hpp": banner + "#pragma once\nnamespace mxfp6_registry {\n"
        + f"inline constexpr int candidate_count = {len(candidates)};\n"
        + f"inline constexpr char candidate_abi[] = {json.dumps(policy['candidate_abi'])};\n"
        + "}\n",
        "w6a8_candidates.inc": banner + "\n".join(switch) + "\n",
        "w6a8_exact.inc": banner + "\n".join(emit_rules(policy["exact_rules"])) + "\n",
        "_w6a8_registry.py": "\n".join(metadata) + "\n",
    }


def write_if_changed(path: Path, content: str, check: bool) -> None:
    if path.exists() and path.read_text() == content:
        return
    if check:
        raise SystemExit(f"stale generated file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--cpp-dir", type=Path)
    parser.add_argument("--python-output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.cpp_dir is None and args.python_output is None:
        parser.error("specify --cpp-dir and/or --python-output")
    for name, content in generate(load_policy(args.source)).items():
        if name.endswith((".inc", ".hpp")) and args.cpp_dir is not None:
            write_if_changed(args.cpp_dir / name, content, args.check)
        elif name.endswith(".py") and args.python_output is not None:
            write_if_changed(args.python_output, content, args.check)


if __name__ == "__main__":
    main()
